// Generates tokens.css: the Ignorance theme's design tokens that the plugin's stylesheets read, so the
// plugin keeps its look under any theme. Every rule is scoped to body.ib-standalone, which the plugin
// sets only while the Ignorance theme is not active; with the theme on, its own tokens win untouched.
//   node scripts/gen-tokens.mjs [theme parts dir]     default: ../theme/src/parts
import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import postcss from "postcss";

const here = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const partsDir = path.resolve(here, process.argv[2] || "../theme/src/parts");
const SCOPE = "body.ib-standalone";
const TOKEN = /--ib-[a-z0-9-]+/g;

const sheet = name => readFile(path.join(here, name), "utf8");
const plugin = (await Promise.all(["styles.css", "theme-features.css"].map(sheet))).join("\n");
const declaredByPlugin = new Set();
postcss.parse(plugin).walkDecls(/^--ib-/, decl => declaredByPlugin.add(decl.prop));
for (const file of await listSources(path.join(here, "src"))) {
  for (const match of (await readFile(file, "utf8")).matchAll(/setProperty\(\s*["'`](--ib-[a-z0-9-]+)/g)) declaredByPlugin.add(match[1]);
}

// Token declarations of the theme, in cascade order, with the selector and at-rules around them.
const entries = [];
for (const name of (await readdir(partsDir)).filter(name => name.endsWith(".css")).sort()) {
  postcss.parse(await readFile(path.join(partsDir, name), "utf8")).walkDecls(/^--ib-/, decl => {
    const rule = decl.parent;
    if (rule.type !== "rule") return;
    const wrappers = [];
    for (let node = rule.parent; node && node.type === "atrule"; node = node.parent) wrappers.unshift(`@${node.name} ${node.params}`);
    entries.push({ prop: decl.prop, value: decl.value, selector: rule.selector, wrappers });
  });
}

// The tokens the plugin reads but does not declare, plus everything those resolve through.
const needed = new Set([...plugin.matchAll(/var\(\s*(--ib-[a-z0-9-]+)/g)].map(match => match[1]).filter(name => !declaredByPlugin.has(name)));
for (let grew = true; grew;) {
  grew = false;
  for (const entry of entries) if (needed.has(entry.prop)) for (const [name] of entry.value.matchAll(TOKEN)) {
    if (!needed.has(name) && !declaredByPlugin.has(name)) { needed.add(name); grew = true; }
  }
}

function scope(selector) {
  return selector.split(",").map(part => {
    const s = part.trim();
    const head = s.match(/^(:root|html|body)((?:[.:[][^\s>+~]*)?)(.*)$/);
    if (head) return `${SCOPE}${head[2]}${head[3]}`;
    const mode = s.match(/^(\.theme-(?:light|dark)(?:[.:[][^\s>+~]*)?)(.*)$/);
    if (mode) return `${SCOPE}${mode[1]}${mode[2]}`;
    return `${SCOPE} ${s}`;
  }).join(",\n");
}

const root = postcss.root();
let last = null;
for (const entry of entries) {
  if (!needed.has(entry.prop)) continue;
  const selector = scope(entry.selector);
  const key = `${entry.wrappers.join("|")}\n${selector}`;
  if (!last || last.key !== key) {
    let parent = root;
    for (const wrapper of entry.wrappers) {
      const [, name, params] = wrapper.match(/^@(\S+)\s*(.*)$/);
      const at = postcss.atRule({ name, params });
      parent.append(at);
      parent = at;
    }
    const rule = postcss.rule({ selector });
    parent.append(rule);
    last = { key, rule };
  }
  last.rule.append(postcss.decl({ prop: entry.prop, value: entry.value }));
}

const missing = [...needed].filter(name => !entries.some(entry => entry.prop === name)).sort();
const header = `/* Generated by scripts/gen-tokens.mjs from the Ignorance theme; do not edit by hand.
 * Design tokens for using the plugin without the theme (body.ib-standalone). */\n`;
await writeFile(path.join(here, "tokens.css"), header + root.toString().trim() + "\n");
console.log(`tokens.css: ${needed.size - missing.length} tokens`);
if (missing.length) console.log(`not declared anywhere: ${missing.join(" ")}`);

async function listSources(dir) {
  const out = [];
  for (const item of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, item.name);
    if (item.isDirectory()) out.push(...await listSources(full));
    else if (item.name.endsWith(".ts")) out.push(full);
  }
  return out;
}
