export const GALLERY_FILE = "功能样例";

export function galleryText(language: Language): string {
  const t = T[language];
  const row = (cells: string[]) => `| ${cells.join(" | ")} |`;
  const lines: string[] = [
    "---", "cssclasses: [ib-wide-tables]", "---", `# ${t.title}`, "", t.intro, "",
    `## ${t.classes}`, "", t.classesHint, "",
    row([t.colName, t.colEffect, t.colNeeds]), row(["---", "---", "---"]),
    ...NOTE_CLASSES.map(item => row([`\`${item.name}\``, CLASS_TEXT[language][item.name], item.source === "theme" ? t.theme : t.plugin])), "",
    `## ${t.statuses}`, "", t.statusesHint, "",
    ...STATUSES.map(item => `- [${item.mark}] \`[${item.mark}]\` ${language === "zh" ? item.zh : item.en}`), "",
    `## ${t.callouts}`, "",
    ...CALLOUTS.flatMap(item => [`> [!${item.type}] ${item.type}`, `> ${language === "zh" ? item.zh : item.en}`, ""]),
    `> [!aside] ${t.asideTitle}`, `> ${t.aside}`, "",
    `## ${t.long}`, "", t.longHint, "",
    row(Array.from({ length: 12 }, (_, i) => `${language === "zh" ? "列" : "Col"} ${i + 1}`)), row(Array.from({ length: 12 }, () => "---")),
    row(Array.from({ length: 12 }, (_, i) => `${language === "zh" ? "一段较长的内容" : "A longer piece of content"} ${i + 1}`)), "",
    `${t.longTable} {#tab-wide}`, "", t.longCode, "", "```js",
    "const message = [\"a very long line of code that goes on and on\", \"so you can see whether it scrolls or wraps\", \"in the pane you are using right now\"].join(\" \");",
    "```", "",
    `## ${t.nest}`, "", `> ${t.nestQuote}`, ">", `> > ${t.nestInner}`, ">", `> ${t.nestCode}`, ">", "> ```", "> const a = 1;", "> ```", "", t.end, ""
  ];
  return lines.join("\n");
}
