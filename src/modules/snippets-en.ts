/** The template body with every Chinese run replaced by its English text. Placeholder marks ⟦…⟧ are kept. */
export function localizeSnippetBody(body: string, table: Readonly<Record<string, string>> = SNIPPET_EN): string {
  return body.replace(/[一-龥]+/g, run => table[run] ?? run);
}
